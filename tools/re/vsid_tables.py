# Writes src/core/cards/vsid_tables.cpp from the TVC256k++ firmware's tvc-sid-internal.h: the ADSR rate and
# volume-divider tables (Bakisha's STM32-SID-Player, GPL-3.0) and the combined-waveform AND mask (reSID, GPL-2.0-or-later).
# usage: python3 -I tools/re/vsid_tables.py <tvc-sid-internal.h> <output .cpp>
import re
import sys

text = open(sys.argv[1], encoding='utf-8').read()
text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
text = re.sub(r'//[^\n]*', '', text)


def table(name):
    body = re.search(name + r'\s*\[\]\s*=\s*\{(.*?)\};', text, re.S).group(1)
    return [int(v, 0) for v in re.findall(r'0x[0-9a-fA-F]+|\d+', body)]


def rows(values, per_row, fmt):
    return ',\n'.join('    ' + ', '.join(fmt % v for v in values[i:i + per_row]) for i in range(0, len(values), per_row))


lfsr15 = table('ADSR_LFSR15')
divider = table('ADSR_Volume2LFSR5')
mask = table('AND_mask')
assert (len(lfsr15), len(divider), len(mask)) == (16, 256, 4096)

out = f'''// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by tools/re/vsid_tables.py from the TVC256k++ firmware 0.24 (sources/firmware/TVC-IO/tvc-sid-internal.h,
// commit 4580b14): ADSR_LFSR15 and ADSR_Volume2LFSR5 come from Bakisha's STM32-SID-Player (GPL-3.0), AND_mask from
// reSID by Dag Lem (GPL-2.0-or-later). Data only; THIRD_PARTY.md credits them.
#include "core/cards/vsid.hpp"

namespace freetvc {{

const std::array<std::uint32_t, 16> VSid::kAdsrRate = {{
{rows(lfsr15, 8, '%d')}}};

const std::array<std::uint8_t, 256> VSid::kVolumeDivider = {{
{rows(divider, 16, '0x%02X')}}};

const std::array<std::uint8_t, 4096> VSid::kAndMask = {{
{rows(mask, 16, '0x%02X')}}};

}}  // namespace freetvc
'''
open(sys.argv[2], 'w', encoding='utf-8').write(out)
